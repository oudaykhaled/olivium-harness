  # cd, pushd and popd move the directory later pieces resolve from. Leaving the
  # project is refused. A wildcard is expanded on disk and followed when it names one
  # directory; a directory the guard cannot know (a $VARIABLE, $( ), a wildcard that
  # names no single directory, a bare name with CDPATH set) refuses what follows it.
  function cd_to(w, n, k, cmd,    t, here) {
    for (k++; k <= n && w[k] ~ /^-[LPe@]+$/; k++) ;
    if (k <= n && w[k] == "--") k++
    if (k <= n && w[k] ~ /^[0-9]*[<>]/) k = n + 1
    # popd and a bare pushd go back to a directory this command did not push: unknown.
    if (cmd == "popd") {
      if (k <= n || NSTACK == 0) deny("changes to a directory from the directory stack")
      else { OLD = cwd; cwd = STACK[NSTACK--] }
      return
    }
    if (k > n) {
      if (cmd == "cd") deny("changes to the home directory (cd with no directory)")
      else if (NSTACK == 0) deny("changes to a directory from the directory stack")
      else { t = STACK[NSTACK]; STACK[NSTACK] = cwd; OLD = cwd; cwd = t }
      return
    }
    t = w[k]
    if (t == "-") {
      if (OLD == "") deny("returns to the previous directory, which may be outside the project")
      else { here = cwd; cwd = OLD; OLD = here }
      return
    }
    if (t ~ /^[+-][0-9]+$/) { deny("changes to a directory from the directory stack"); return }
    if (t ~ /^~/) return
    if (t ~ /[$`]/ || (CDPATH_SET && t !~ /^\.?\.?\//)) { LOST = 1; return }
    if (t ~ /[*?[]/) {
      here = cd_glob(cwd, t)
      if (here == "") { LOST = 1; return }
      if (!inside(here)) { deny("changes to a directory outside the project: " t); return }
    }
    else here = absolute(t)
    if (!inside(here)) { deny("changes to a directory outside the project: " t); return }
    if (cmd == "pushd") STACK[++NSTACK] = cwd
    OLD = cwd; cwd = here
  }
  # One pipeline piece, as the shell words parse() found in it. Quote marks left
  # inside a word (text quoted within other quotes) are dropped, so a command quoted
  # inside the text of a program is still recognised.
  function wrapped(    n, k, w, i, m, part, j, t, cmd) {
    n = 0
    for (i = 1; i <= NW; i++) {
      m = split(WT[i], part, /[ \t\n]+/)
      for (j = 1; j <= m; j++) { t = part[j]; gsub(/^["\047]+|["\047]+$/, "", t); if (t != "") w[++n] = t }
    }
    WRITES = 0
    k = lead(w, n, 1)
    if (!k) return
    if (LOST) deny("runs a command after a cd the guard cannot follow ($VARIABLE, $( ) or a wildcard that names no single directory)")
    refuse(w, n, k)
    cmd = base(w[k])
    if (cmd ~ /^(cd|pushd|popd)$/) cd_to(w, n, k, cmd)
  }
  # The word a piece runs as its program, past assignments, redirections and simple
  # wrappers. Its path is not looked up: a program resolving outside the project (a
  # virtual environment python) is not a path the command reads or writes.
  function program(    i) {
    for (i = 1; i <= NW; i++) {
      if (WT[i] ~ /^[A-Za-z_][A-Za-z0-9_]*=/) continue
      if (WT[i] ~ /^[0-9]*(<|>|>>|<<|<<-|<<<|<>|>\|)$/) { i++; continue }
      if (base(WT[i]) ~ /^(env|command|builtin|exec|nohup|nice|time|timeout|stdbuf|setsid|xargs|if|then|else|elif|do|while|until|!)$/ || WT[i] ~ /^-/ || WT[i] ~ /^[0-9.]+[smhd]?$/) continue
      return i
    }
    return 0
  }
  # Shell words. A word joins its unquoted and quoted parts, as the shell does, so
  # `.e""nv` is `.env`; WQ and WU count its quoted and unquoted parts, WG marks an
  # unquoted wildcard. Redirection operators are words of their own.
  function wend() {
    if (WOPEN) { NW++; WT[NW] = WCUR; WQ[NW] = WQN; WU[NW] = WUN; WG[NW] = WGL }
    WCUR = ""; WQN = 0; WUN = 0; WGL = 0; WOPEN = 0
  }
  function wplain(t) {
    while (t != "") {
      if (match(t, /^[ \t\n]+/)) { wend(); t = substr(t, RLENGTH + 1); continue }
      if (match(t, /^[<>]+\|?/)) {
        if (!(WOPEN && WQN == 0 && WCUR ~ /^[0-9]+$/)) wend()
        WCUR = WCUR substr(t, 1, RLENGTH); WUN++; WOPEN = 1; wend(); t = substr(t, RLENGTH + 1); continue
      }
      match(t, /^[^ \t\n<>]+/)
      if (substr(t, 1, RLENGTH) ~ /[*?[]/) WGL = 1
      WCUR = WCUR substr(t, 1, RLENGTH); WUN++; WOPEN = 1; t = substr(t, RLENGTH + 1)
    }
  }
  # Splits a piece of a line into unquoted text (PLAIN), quoted text (QUOTED), its
  # shape with quote marks dropped and quoted punctuation blanked (SHAPE), where a
  # here-document tag can be found, and shell words. The quote state Q carries on, as
  # in the shell.
  function parse(s,    c, t) {
    PLAIN = ""; QUOTED = ""; SHAPE = ""; NW = 0; WCUR = ""; WUN = 0; WGL = 0
    WQN = (Q != ""); WOPEN = WQN
    while (s != "") {
      if (Q == "") {
        if (match(s, /^[^\\\047"]+/)) { t = substr(s, 1, RLENGTH); s = substr(s, RLENGTH + 1); PLAIN = PLAIN t; SHAPE = SHAPE t; wplain(t); continue }
        c = substr(s, 1, 1)
        if (c == "\\") { t = substr(s, 2, 1); s = substr(s, 3); PLAIN = PLAIN t; SHAPE = SHAPE t; WCUR = WCUR t; WUN++; WOPEN = 1; continue }
        Q = c; PLAIN = PLAIN " "; s = substr(s, 2); WQN++; WOPEN = 1; continue
      }
      if ((Q == "\047" && match(s, /^[^\047]+/)) || (Q == "\"" && match(s, /^[^"\\]+/))) {
        t = substr(s, 1, RLENGTH); s = substr(s, RLENGTH + 1); QUOTED = QUOTED t; WCUR = WCUR t
        gsub(/[^A-Za-z0-9_.-]/, "_", t); SHAPE = SHAPE t; continue
      }
      c = substr(s, 1, 1)
      if (c == "\\") { t = substr(s, 2, 1); s = substr(s, 3); QUOTED = QUOTED t; WCUR = WCUR t; gsub(/[^A-Za-z0-9_.-]/, "_", t); SHAPE = SHAPE t; continue }
      Q = ""; QUOTED = QUOTED " "; s = substr(s, 2)
    }
    wend()
  }
  # A line, piece by piece. A ( ) group or $( ) keeps its cd to itself. Each word that
  # could be a path is looked up on disk from the directory the piece runs in, as a
  # write when the command of the piece writes or the word follows > or >>.
  function check_line(l,    rest, seg, sep, shape, i, t, j, here, p, prog, v) {
    if (l ~ /\$\{?HOME([^A-Za-z0-9_]|$)/) deny("names the home directory")
