  # A file a command writes through an option or operand (sort -o, the second operand
  # of uniq, find -fprint, dd of=): refused when it is the .claude settings or hooks,
  # and looked up on disk as a write, so a link to them counts too. An absolute path
  # outside the project is left to the word check (/etc is refused, /tmp and /dev/stdout not).
  function output(t) {
    if (t == "" || t ~ /[$`]/ || t ~ /^~/) return
