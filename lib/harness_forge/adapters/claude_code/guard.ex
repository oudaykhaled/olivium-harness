      }
    }
    return shape
  }
  # Here-document bodies are data and are skipped, unless a shell reads them.
  function check_command(cmd,    nl, line, k, rest, shape, tag, ntag, body, tags, strip, shell) {
    if (cmd ~ /(^|[^A-Za-z0-9_])CDPATH=/) deny("sets CDPATH, which changes where cd goes")
