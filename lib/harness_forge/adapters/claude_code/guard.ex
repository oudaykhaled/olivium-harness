defmodule HarnessForge.Adapters.ClaudeCode.Guard do
  @moduledoc """
  Renders `.claude/hooks/olivium-guard.sh`, a PreToolUse hook that only refuses.

  It never approves a call. When it has no objection it prints nothing and exits 0, so
  Claude Code's own permission system (deny rules, the allow list and its built-in
  per-command checks) decides exactly as if the hook were not there. The hook command
  in `settings.json` (`ClaudeCode.guard_command/1`) sets `PATH` to `/usr/bin:/bin`,
  runs the file only while its SHA-256 is the one generated with it, and passes on only
  the guard's exact refusal line. So neither a parser mistake, nor a changed guard file,
  nor a `grep` placed earlier on the session's `PATH` lets the hook approve a call or
  change its input: on any call it can only add a refusal, as long as `/bin/sh` and
  the programs in `/usr/bin` and `/bin` are the system's own and no other process can
  write to the hook's output. A background process that writes into the command's
  pipes can make the checksum check fail, which turns the guard off for that call
  (Claude Code's rules then decide alone). This does not cover
  Claude Code's settings files, which a program the agent runs can rewrite and Claude
  Code reloads during a session, with or without the guard.

  It refuses a tool call that names a secret file (directly, through a link or by a
  wildcard), a path outside the project (the system's scratch directories, `/tmp`,
  `/var/tmp` and `/dev/shm`, are not outside), a recursive or bulk delete, a branch deletion
  or overwrite, a package download, a denied command hidden behind a wrapper (`uv run`,
  `xargs`, `sh -c`, `timeout`, `find -exec`, a sed `e` command), and anything that would
  remove, overwrite or stash this project's `.claude` settings and hooks, including an
  output file named inside a program's arguments (`sed w`, `sort -o`, `uniq`'s second
  operand, `awk` `print > "file"`, `find -fprint`, `dd of=`). Writes made by a program
  it cannot read (`python3`, `node`) are not seen.

  Claude Code 2.1.311 asks before every `cd dir && cmd` compound while any `Read(...)`
  deny rule exists, so the settings carry no read deny rules; the spec's read denies are
  enforced here instead. Edit denies stay as rules too.

  Besides the call's text, the hook looks at the file system: it resolves symbolic
  links (`realpath`), expands unquoted wildcards in the directory the command runs in,
  and checks that a package `npx`, `bunx` or `npm exec` would run is installed, in
  `node_modules` or as a bin the project's own `package.json` declares (a `bin` object
  key, or a `bin` string with that `name`). That `package.json` (a regular file of at
  most 1 MiB, not a link) is the only file it reads, as data, and only for that check.

  It pattern-matches the text of a call and is not a sandbox: a program the agent runs
  (`python3`, `node`, `uv run`, `sed`, `awk`, `find`) can still open, write or delete
  any file the user can and run any command. It runs POSIX `sh`, `awk` and `realpath`
  from `/usr/bin` and `/bin`, and never touches the network. Without `realpath` links
  are not followed.
  """

  @path ".claude/hooks/olivium-guard.sh"

  @header """
  #!/bin/sh
  # Generated by Olivium Harness. A PreToolUse guard that only refuses: a tool call
  # that names a secret file, a path outside the project (other than /tmp scratch), a
  # recursive or bulk delete, a branch deletion, a package download, a denied command
  # behind a wrapper, or a change that would remove, overwrite or stash .claude. It
  # never approves anything: with no objection it prints nothing and the permission
  # rules of Claude Code decide. The hook command in .claude/settings.json runs this
  # file only while its SHA-256 is the generated one and passes on only its refusal
  # line; to change what it refuses, change the spec and generate again. It reads the
  # text of each call and looks up links and wildcards on disk; the only file it reads
  # is package.json at the project root, as data, to see whether a package npx would
  # run is a bin of the project itself. It pattern-matches and is not a sandbox: a
  # program the agent runs can still do anything you can.
  exec awk -v dir="${CLAUDE_PROJECT_DIR%/}" '
  """

  # Whether the project's own package.json provides the bin OLIVIUM_BIN: a top-level
  # "bin" object with that key, or a "bin" string with "name" equal to it. npx runs a
  # project's own bin without downloading it. The file is read as data only: its text is
  # split into JSON tokens and compared, never evaluated. Exit 0 when it provides it.
  @provides_bin ~S"""
  { s = s $0 "\n" }
  END {
    p = ENVIRON["OLIVIUM_BIN"]; n = length(s); i = 1; d = 0; m = 0
    while (i <= n) {
      if (match(substr(s, i, 4096), /^[^]["{},:]+/)) { i += RLENGTH; continue }
      c = substr(s, i, 1)
      if (c == "\"") {
        st = ++i
        while (i <= n) {
          if (match(substr(s, i, 4096), /^[^"\\]+/)) { i += RLENGTH; continue }
          if (substr(s, i, 1) == "\\") { i += 2; continue }
          break
        }
        if (d <= 2) { m++; T[m] = "s"; V[m] = substr(s, st, i - st); D[m] = d }
        i++; continue
      }
      if (c == "{" || c == "[") { if (d <= 2) { m++; T[m] = c; D[m] = d } d++ }
      else if (c == "}" || c == "]") { d--; if (d <= 2) { m++; T[m] = c; D[m] = d } }
      else if (d <= 2) { m++; T[m] = c; D[m] = d }
      i++
    }
    for (k = 1; k <= m; k++) {
      if (T[k] != "s" || D[k] != 1 || T[k + 1] != ":") continue
      if (V[k] == "name" && T[k + 2] == "s") name = V[k + 2]
      if (V[k] != "bin") continue
      if (T[k + 2] == "s") sbin = 1
      else if (T[k + 2] == "{")
        for (j = k + 3; j <= m && !(T[j] == "}" && D[j] == 1); j++)
          if (T[j] == "s" && D[j] == 2 && T[j + 1] == ":" && V[j] == p) obin = 1
    }
    exit !(p != "" && (obin || (sbin && name == p)))
  }
  """

  # Runs once per call, from awk, with each argument single-quoted. Queries come in
  # fours: mode, purpose (r read, w write), directory, word. It prints the project's
  # real path (D), each existing path an unquoted wildcard expands to (G), the one
  # directory a wildcard cd names (C), a package npx would download (N), then R and the
  # real path of every path read, then W and the real path of every path written. A
  # path that does not exist yet is replaced by its nearest existing parent. The only
  # file it reads is the project's package.json (a regular file of at most 1 MiB, not
  # a link), as data, when npx would run a package that is not installed: a bin the
  # project itself provides counts as installed. Whether npx finds a package on PATH is
  # looked up in the session's PATH, which the hook command passes as OLIVIUM_PATH.
  @helper """
  P=$1
  shift
  unset CDPATH
  nl='
  '
  IFS=$nl
  set -f
  r=$(realpath -- "$P" 2>/dev/null) && printf 'D %s\\n' "$r"
  L=
  W=
  t=0
  while [ $# -ge 4 ]; do
    m=$1 p=$2 c=$3 w=$4
    shift 4
    cd -- "$c" 2>/dev/null || continue
    case $m in
    n)
      case $(PATH=${OLIVIUM_PATH:-$PATH}; command -v "$w" 2>/dev/null) in /*) continue ;; esac
      x=$c
      while :; do
        if [ -e "$x/node_modules/.bin/$w" ] || [ -e "$x/node_modules/$w/package.json" ]; then continue 2; fi
        case $x in "$P" | / | '') break ;; esac
        x=${x%/*}
      done
      f=$P/package.json
      if [ -f "$f" ] && [ ! -L "$f" ] && [ $(($(wc -c <"$f"))) -le 1048576 ] &&
        OLIVIUM_BIN=$w awk '#{@provides_bin}' "$f" 2>/dev/null; then continue; fi
      printf 'N %s\\n' "$w"
      ;;
    c)
      set +f
      k=0
      for f in $w; do
        if [ -d "$f" ]; then k=$((k + 1)); x=$f; fi
      done
      set -f
      if [ "$k" -eq 1 ] && x=$(cd -- "$x" 2>/dev/null && pwd -P); then printf 'C %s\\n' "$x"; fi
      ;;
    g)
      set +f
      for f in $w; do
        [ -e "$f" ] || [ -L "$f" ] || continue
        t=$((t + 1))
        [ "$t" -gt 2000 ] && break
        case $f in /*) ;; *) f=$PWD/$f ;; esac
        printf 'G%s %s\\n' "$p" "$f"
        if [ "$p" = w ]; then W=$W$f$nl; else L=$L$f$nl; fi
      done
      set -f
      ;;
    *)
      case $w in /*) f=$w ;; *) f=$PWD/$w ;; esac
      while [ -n "$f" ] && [ ! -e "$f" ] && [ ! -L "$f" ]; do f=${f%/*}; done
      [ -n "$f" ] || continue
      if [ "$p" = w ]; then W=$W$f$nl; else L=$L$f$nl; fi
      ;;
    esac
  done
  echo R
  [ -n "$L" ] && realpath -- $L 2>/dev/null
  echo W
  [ -n "$W" ] && realpath -- $W 2>/dev/null
  exit 0
  """

  @functions ~S"""
  function field(s, key,    i, n, c, e, out) {
    if (!match(s, "\"" key "\"[ \t]*:[ \t]*\"")) return ""
    i = RSTART + RLENGTH; n = length(s); out = ""
    while (i <= n) {
      if (match(substr(s, i, 4096), /^[^"\\]+/)) { out = out substr(s, i, RLENGTH); i += RLENGTH; continue }
      c = substr(s, i, 1)
      if (c == "\"") break
      e = substr(s, i + 1, 1); i += 2
      if (e == "n") out = out "\n"
      else if (e == "u") { out = out " "; i += 4 }
      else if (e == "t" || e == "r" || e == "b" || e == "f") out = out " "
      else out = out e
    }
    return out
  }
  function base(w) { sub(/.*\//, "", w); return w }
  function secret(path, name, whole,    n, k, part) {
    if (name != "") { n = split(path, part, "/"); for (k = 1; k <= n; k++) if (part[k] ~ name) return 1 }
    return whole != "" && path ~ whole
  }
  function normal(path,    n, k, part, m, kept, out) {
    n = split(path, part, "/"); m = 0
    for (k = 1; k <= n; k++) {
      if (part[k] == "" || part[k] == ".") continue
      if (part[k] == "..") { if (m > 0) m--; continue }
      kept[++m] = part[k]
    }
    out = ""
    for (k = 1; k <= m; k++) out = out "/" kept[k]
    return out == "" ? "/" : out
  }
  function under(path, root) { return root != "" && (path == root || substr(path, 1, length(root) + 1) == root "/") }
  function inside(path) { return under(path, dir) || under(path, rdir) }
  # A path as the secret patterns see it: relative to the project when inside it, so a
  # project kept under a directory called `secrets` is not itself a secret.
  function rel(path) {
    if (path !~ /^\//) return path
    path = normal(path)
    if (under(path, dir)) return substr(path, length(dir) + 2)
    if (under(path, rdir)) return substr(path, length(rdir) + 2)
    return path
  }
  function absolute(path) { return from(cwd, path) }
  function from(here, path) { return path ~ /^\// ? normal(path) : normal(here "/" path) }
  function device(path) { return path ~ /^\/dev\/(null|zero|random|urandom|tty|std(in|out|err)|fd\/[0-9]+)$/ }
  # Scratch directories of the system: /tmp, /var/tmp, /dev/shm, and on macOS their real
  # paths under /private and the per-user temporary directory. Scratch files belong
  # there, not in the project; a link out of them and a secret name are still refused.
  function scratch(path) { return path ~ /^\/(private\/)?(var\/)?tmp(\/|$)/ || path ~ /^\/dev\/shm(\/|$)/ || path ~ /^\/(private\/)?var\/folders\/[^\/]+\/[^\/]+\/T(\/|$)/ }
  # The Claude Code settings and hooks of this project. Removing, overwriting or
  # stashing them turns the guard, the Stop hook and the allow list off. `whole` also
  # protects the .claude directory itself, for a path named exactly; a resolved path
  # may be the nearest existing parent of a new file, so only hooks and settings count.
  function protected(path, whole,    r) {
    if (!inside(path)) return 0
    r = rel(path)
    if (whole && r == ".claude") return 1
    return r ~ /^\.claude\/(hooks(\/.*)?|settings(\.local)?\.json)$/
  }
  # A word in a command: ~ and $HOME are outside; an absolute path is outside when it
  # starts at a system directory or next to the project; a relative one when .. leaves
  # it (a quoted .. alone is more often reStructuredText or a range than a path). Claude
  # Code keeps its transcripts and long tool output in a directory of its own, which
  # is not outside either.
  function outside(word, quoted,    p, top) {
    if (word ~ /^~/ && (!quoted || word ~ /^~(\/|$)/)) return 1
    if (word ~ /^\//) {
      p = normal(word)
      if (under(p, dir) || device(p) || under(p, transcripts) || scratch(p)) return 0
      top = p; sub(/^\//, "", top); sub(/\/.*/, "", top)
      return top != "" && (top ~ SYSTEM || top == dirtop)
    }
    if (word ~ /(^|\/)\.\.(\/|$)/ && (!quoted || word ~ /\//)) return !under(normal(cwd "/" word), dir)
    return 0
  }
  function deny(why) { if (reason == "") reason = why }
  # A refusal to fetch a package. The message names the tool and tells the agent it is
  # not installed here, so it continues without it instead of trying another way.
  function fetching(before, name, after,    t) {
    if (reason != "") return
    t = toolname(name)
    reason = before " " (t != "" ? t : "a package") " from the package registry" after
    TOOL = t; FETCH = 1
  }
  # A package name as a message may show it: no version, extras or URL; "" when unclear.
  function toolname(t,    at) {
    at = (substr(t, 1, 1) == "@")
    if (at) t = substr(t, 2)
    sub(/\[.*$/, "", t)
    sub(/[=<>~!@;, ].*$/, "", t)
    if (at) t = "@" t
    if (length(t) > 64 || t !~ "^@?[A-Za-z0-9][A-Za-z0-9._/+-]*$") return ""
    return t
  }
  # The first word from w[j] that is not an option or the argument of one in args.
  function pkg(w, n, j, args,    a) {
    for (; j <= n; j++) {
      a = w[j]
      if (a == "--") return w[j + 1]
      if (a ~ /^--from=/) return substr(a, 8)
      if (a == "--from") return w[j + 1]
      if (args != "" && a ~ args) { j++; continue }
      if (a !~ /^-/) return a
    }
    return ""
  }
  # The package an npx, bunx or npm exec flag at w[j] makes it download.
  function npxname(w, n, j,    a) {
    a = w[j]
    if (a ~ /^--package=/) return substr(a, 11)
    if (a ~ /^(-p|--package)$/) return w[j + 1]
    for (j++; j <= n; j++) {
      a = w[j]
      if (a == "--") return w[j + 1]
      if (a ~ /^--package=/) return substr(a, 11)
      if (a ~ /^(-p|--package)$/) return w[j + 1]
      if (a ~ OPTARG["npx"]) { j++; continue }
      if (a !~ /^-/) return a
    }
    return ""
  }
  function guarded(path) { deny("removes, overwrites or stashes the Claude Code settings or hooks of this project (.claude): " path) }
  # Quoted text is code or a pattern more often than a path, so a quoted word counts
  # as a secret only when it looks like a path. A path attached to an option
  # (-o/tmp/x) or to a sed w or r command (w/tmp/x) is checked on its own too.
  function check_words(text, quoted,    n, k, w, v) {
    gsub(/[ \t\047"`;&|<>(){},=:\\]+/, " ", text)
    n = split(text, w, " ")
    for (k = 1; k <= n; k++) {
      check_word(w[k], quoted)
      v = w[k]
      if (v ~ /^-[A-Za-z0-9]+[.\/~]/) sub(/^-[A-Za-z0-9]+/, "", v)
      else if (v ~ /^[0-9,$]*[wWrR]\//) sub(/^[0-9,$]*[wWrR]/, "", v)
      if (v != w[k]) check_word(v, 0)
    }
  }
  function check_word(word, quoted) {
    if ((!quoted || word ~ /^[.~]|\//) && secret(rel(word), ANY_NAME, ANY_PATH)) deny("names a secret file: " word)
    else if (outside(word, quoted)) deny("names a path outside the project: " word)
  }
  # A shell single-quoted word, for the helper arguments.
  function sq(s,    out, i) {
    out = ""
    while ((i = index(s, "\047")) > 0) { out = out substr(s, 1, i - 1) "\047\\\047\047"; s = substr(s, i + 1) }
    return "\047" out s "\047"
  }
  # A path to look up on disk: m is l (follow links), g (expand the wildcard, then
  # follow links) or n (a package npx would run); p is r or w.
  function query(m, p, c, w,    key) {
    key = m SUBSEP p SUBSEP c SUBSEP w
    if (key in ASKED || NQ >= 200) return
    ASKED[key] = 1; NQ++; QM[NQ] = m; QP[NQ] = p; QC[NQ] = c; QW[NQ] = w
  }
  function probe(    cmd, k, line, part) {
    cmd = "sh -c " sq(HELPER) " olivium-guard " sq(dir)
    for (k = 1; k <= NQ; k++) cmd = cmd " " QM[k] " " QP[k] " " sq(QC[k]) " " sq(QW[k])
    NFOUND = 0; part = ""
    while ((cmd | getline line) > 0) {
      if (line == "R" || line == "W") part = line
      else if (part != "") { FK[++NFOUND] = "R"; FP[NFOUND] = (part == "W") ? "w" : "r"; FV[NFOUND] = line }
      else if (line ~ /^D /) rdir = substr(line, 3)
      else if (line ~ /^N /) { FK[++NFOUND] = "N"; FP[NFOUND] = "r"; FV[NFOUND] = substr(line, 3) }
      else if (line ~ /^G[rw] /) { FK[++NFOUND] = "G"; FP[NFOUND] = substr(line, 2, 1); FV[NFOUND] = substr(line, 4) }
    }
    close(cmd)
  }
  # The one directory a cd to a wildcard reaches, as its real path, or "".
  function cd_glob(c, t,    cmd, line, found) {
    cmd = "sh -c " sq(HELPER) " olivium-guard " sq(dir) " c r " sq(c) " " sq(t)
    found = ""
    while ((cmd | getline line) > 0) {
      if (line ~ /^D /) rdir = substr(line, 3)
      else if (line ~ /^C /) found = substr(line, 3)
    }
    close(cmd)
    return found
  }
  # A Read, Edit or Write path inside the project, through any link in it.
  function linked(path, name, whole, verb, write,    k) {
    query("l", write ? "w" : "r", cwd, path); probe()
    for (k = 1; k <= NFOUND; k++) {
      if (FK[k] != "R") continue
      if (inside(FV[k])) {
        if (secret(rel(FV[k]), name, whole)) deny("names a secret file through a link: " path)
        else if (write && protected(FV[k], 0)) guarded(path)
      }
      else if (secret(FV[k], name, whole)) deny("names a secret file through a link: " path)
      else if (!scratch(FV[k])) deny(verb " outside the project through a link: " path)
    }
  }
  # Past the options of a wrapper or runner, and the argument each option takes.
  function opts(w, n, k, who,    a) {
    a = OPTARG[who]
    for (; k <= n && w[k] ~ /^-./; k++) {
      if (w[k] == "--") return k + 1
      if (a != "" && w[k] ~ a) k++
    }
    if (who == "timeout" && k <= n && w[k] ~ /^[0-9.]+[smhd]?$/) k++
    return k
  }
  # The command a pipeline piece runs, past assignments, redirections, shell keywords,
  # wrappers, shells and runners. Each step is checked against the denied commands and
  # the package downloaders; 0 when there is no command or it was refused. XARGS notes
  # that the command takes its arguments from a list.
  function lead(w, n, k,    b, j, rest) {
    XARGS = 0
    while (k <= n) {
      b = base(w[k])
      rest = b; for (j = k + 1; j <= n; j++) rest = rest " " w[j]
      if (DENY != "" && match(rest, DENY)) { rest = substr(rest, 1, RLENGTH); sub(/ $/, "", rest); deny("runs a denied command: " rest); return 0 }
      fetch(w, n, k, rest)
      if (w[k] == "command" && w[k + 1] ~ /^-[vV]$/) return 0
      if (w[k] ~ /^[A-Za-z_][A-Za-z0-9_]*=/) { k++; continue }
      if (w[k] ~ /^[0-9]*(<|>|>>|<<|<<-|<<<|<>|>\|)$/) { k += 2; continue }
      if (w[k] ~ /^[0-9]*[<>]/) { k++; continue }
      if (b ~ WRAPPER) { if (b == "xargs") XARGS = 1; k = opts(w, n, k + 1, b); continue }
      if (b ~ RUNNER && w[k + 1] ~ /^(run|exec|dlx|x)$/) { k = opts(w, n, k + 2, b " " w[k + 1]); continue }
      return k
    }
    return 0
  }
  # Runners that download a package the project does not declare and run it. A
  # detected project command is never refused here.
  function fetch(w, n, k, rest,    b, v, j, a) {
    if (PROJECT != "" && rest ~ PROJECT) return
    b = base(w[k]); v = w[k + 1]
    if (b == "uvx") { fetching("downloads and runs", pkg(w, n, k + 1, OPTARG["uvx"]), ""); return }
    if (b == "uv" && v == "tool") { j = k + 2; if (w[j] ~ /^(run|install|upgrade)$/) j++; fetching("downloads and runs", pkg(w, n, j, OPTARG["uvx"]), ""); return }
    if ((b == "pipx" && v ~ /^(run|install)$/) || (b ~ /^(pnpm|yarn)$/ && v == "dlx")) { fetching("downloads and runs", pkg(w, n, k + 2, ""), ""); return }
    if (b == "uv" && v == "run") {
      for (j = k + 2; j <= n && w[j] ~ /^-./; j++) {
        if (w[j] ~ /^(--with|-w)/) {
          a = w[j]
          if (a ~ /^--with-(editable|requirements)/) a = ""
          else if (a ~ /^--with=/) a = substr(a, 8)
          else if (a == "--with" || a == "-w") a = w[j + 1]
          else if (a ~ /^-w./) a = substr(a, 3)
          else a = ""
          fetching("adds", a, " for this run")
          return
        }
        if (w[j] ~ OPTARG["uv run"]) j++
      }
    }
    if (b ~ /^(npx|bunx)$/) node(w, n, k + 1)
    else if (b ~ /^(npm|bun)$/ && v ~ /^(exec|x)$/) node(w, n, k + 2)
  }
  # npx, bunx and npm exec download a package that is not installed, without asking
  # when there is no terminal.
  function node(w, n, j,    a, name) {
    for (; j <= n; j++) {
      a = w[j]
      if (a ~ /^(-y|--yes|-p|--package)$/ || a ~ /^--(yes|package)=/) { fetching("downloads and runs", npxname(w, n, j), ""); return }
      if (a ~ /^(--no|--no-install|-c|--call)$/) return
      if (a == "--") { j++; break }
      if (a ~ OPTARG["npx"]) { j++; continue }
      if (a !~ /^-/) break
    }
    if (j > n) return
    name = w[j]
    if (name ~ /^[.\/]/ || name ~ /[$`]/) return
    if (substr(name, 2) ~ /@/ || name ~ /:/) { fetching("downloads and runs", name, ""); return }
    if (!LOST) query("n", "r", cwd, name)
  }
  # The first package an install command names that is not a local path.
  function named(w, n, j, args,    a) {
    for (; j <= n; j++) {
      a = w[j]
      if (a ~ /^(-e|--editable)$/) { j++; if (j <= n && w[j] !~ /^[.\/]/) return w[j]; continue }
      if (a ~ /^[0-9]*(<|>|>>|<>|>\|)$/ || (args != "" && a ~ args)) { j++; continue }
      if (a ~ /^-/ || a ~ /^[.\/]/ || a ~ /^[0-9]*[<>]/ || a ~ /[.](whl|zip|tgz|tar[.]gz)$/) continue
      return a
