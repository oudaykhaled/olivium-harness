        sub(/^>>?[ \t]*"/, "", t); sub(/"$/, "", t)
        if (t !~ /[$`]/ && protected(from(cwd, t), 1)) guarded(t)
      }
    }
  }
  # git stash push or save with untracked files: the generated .claude files are
  # untracked, so they leave the tree with the stash and every hook goes with them.
  function stash(w, n, j,    a) {
    if (j <= n && w[j] ~ /^(push|save)$/) j++
    else if (j <= n && w[j] !~ /^-/) return
    for (; j <= n && w[j] != "--"; j++) {
      a = w[j]
      if ((a ~ /^-[A-Za-z]*[ua]/ && a !~ /^--/) || (length(a) > 2 && (index("--include-untracked", a) == 1 || index("--all", a) == 1)))
        deny("stashes untracked files, which takes the Claude Code settings and hooks of this project (.claude) out of the tree")
    }
  }
  # What the command a piece runs does, once found by lead(). WRITES notes a command
  # that removes, moves or writes the paths it names.
  function refuse(w, n, k,    cmd, j, m, rest, rec, keep, v) {
    cmd = base(w[k])
    rest = cmd; for (m = k + 1; m <= n; m++) rest = rest " " w[m]
    if (cmd ~ WRITER) WRITES = 1
    if (cmd == "git") {
      for (j = k + 1; j <= n && w[j] ~ /^-/; j++) if (w[j] ~ /^(-c|-C|--git-dir|--work-tree|--namespace)$/) j++
      rest = "git"; for (m = j; m <= n; m++) rest = rest " " w[m]
      if (DENY != "" && match(rest, DENY)) { rest = substr(rest, 1, RLENGTH); sub(/ $/, "", rest); deny("runs a denied command: " rest); return }
