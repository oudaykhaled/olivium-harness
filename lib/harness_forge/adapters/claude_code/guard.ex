        if (w[m] ~ /^(([0-9]+|\$)(,([0-9]+|\$))?)?!?e$/ || w[m] ~ /^\/([^\/\\]|\\.)*\/!?e$/ || w[m] ~ /^s\/([^\/\\]|\\.)*\/([^\/\\]|\\.)*\/[gpIiMm0-9]*e/) deny("runs a shell command from a sed script (e)")
