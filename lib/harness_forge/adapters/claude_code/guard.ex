    else if (!LOST && t !~ /^-/ && (t !~ /^\// || under(normal(t), dir) || scratch(normal(t)))) query("l", "w", cwd, t)
  }
  # Files a sed script (w, W, the s///w flag) or an awk program (print > "file")
  # writes, which are not shell words of their own. Best effort: only a path written
  # out in the command counts, from the directory the command starts in.
  function embedded(cmd,    s, t) {
    if (cmd ~ /(^|[^A-Za-z0-9_.-])sed[ \t]/) {
      s = cmd
      while (match(s, /(^|[ \t\n\047";{}!$0-9,]|\/[gpIiMme0-9]*)[wW][ \t]*[^ \t\n\047";}]+/)) {
        t = substr(s, RSTART, RLENGTH); s = substr(s, RSTART + RLENGTH)
