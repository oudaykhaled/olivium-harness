      else if (path != "" && protected(absolute(path), 1)) guarded(path)
      else if (path != "") linked(path, EDIT_NAME, EDIT_PATH, "writes", 1)
    }
    if (reason == "") exit 0
    reason = substr(reason, 1, 200)
    gsub(/[^ -~]/, "?", reason); gsub(/["\\]/, "?", reason)
    # The second sentence ends the detour: a missing tool or a path outside the project
    # is not there to be found, so the agent continues without it. Every refusal stays.
    if (FETCH) tail = (TOOL != "" ? TOOL : "It") " is not installed here; continue without it. Do not install or download tools."
    else if (reason ~ /outside the project|home directory/) tail = "What is outside the project is not available here; continue without it, and put scratch files in /tmp."
    else tail = "Keep work inside the project, put scratch files in /tmp, and leave secrets, the network, the package registry, git history and .claude alone."
    printf "{\"hookSpecificOutput\":{\"hookEventName\":\"PreToolUse\",\"permissionDecision\":\"deny\",\"permissionDecisionReason\":\"Olivium guard: this call %s. %s\"}}\n", reason, tail
  }'
  """

  # Only with `spec.native.test_runner_commands` (design 3.5): the rule refuses, never
  # approves, and a call without `agent_type` (the main session) is not affected.
  @runner_function ~S"""
  # The generated test runner (agent_type olivium-test-runner) may run only its allowed
  # commands: after one optional `cd <dir in the project> && `, an allowed command, then
  # plain words, then optionally ` 2>&1`, then optionally `| tail -n N` or `| head -n N`.
  # A word is a test file or id (`path`, `path::id`, `path:line`) or one of the output
  # and selection flags in RUNNER_FLAGS; any other flag, and any word with `=` or a
  # leading `@`, is refused, since a flag can load or run other code (`pytest -p`,
  # `--config`, `-exec=`). A test file is a relative path without `..` that stays in the
  # project: an absolute path (a file put in /tmp) or `~` is refused, since a tool such
  # as `node --test` runs whatever file it is given. 1 when the call is one of these.
  function runner_words(t, here,    w, m, i, p) {
    m = split(t, w, " ")
    for (i = 1; i <= m; i++) {
      if (w[i] ~ /^-/) { if (index(" " RUNNER_FLAGS " ", " " w[i] " ") == 0) return 0 }
      else if (w[i] ~ /[=@]/) return 0
      else {
        p = w[i]; sub(/:.*/, "", p)
        if (p ~ /^[\/~]/ || ("/" p "/") ~ /\/\.\.\// || !inside(from(here, p))) return 0
      }
    }
    return 1
  }
  function runner_ok(c,    t, k, n, a, here) {
    here = cwd
    if (match(c, /^cd []A-Za-z0-9_.\/:=+@,%[-]+ && /)) {
      t = substr(c, 4, RLENGTH - 7)
      here = from(cwd, t)
      if (!inside(here)) return 0
      c = substr(c, RLENGTH + 1)
    }
    sub(/ [|] (tail|head) -n [1-9][0-9]?[0-9]?$/, "", c)
    sub(/ 2>&1$/, "", c)
    n = split(TEST_RUNNER, a, "|")
    for (k = 1; k <= n; k++) {
      if (c == a[k]) return 1
      if (substr(c, 1, length(a[k]) + 1) == a[k] " ") {
        t = substr(c, length(a[k]) + 2)
        if (t ~ /^[]A-Za-z0-9_.\/:=+@,%[-]+( []A-Za-z0-9_.\/:=+@,%[-]+)*$/ && runner_words(t, here)) return 1
      }
    }
    return 0
  }
  """

  # Flags the test runner may add: output, stop-early and test-selection flags of the
  # common test tools. None loads or runs other code.
  @runner_flags ~w(-q -qq -v -vv -x -s -k -m -t -g -l -rA -ra -rf -- --lf --ff --last-failed --failed-first --exitfirst --maxfail=1 --tb=short --tb=line --tb=no --no-header --bail --grep --testNamePattern --reporter=dot --reporter=spec --silent --verbose --quiet --trace --failed --stale --color=never --no-color --colors=false)

  # With generated skills or subagents (spec.native.items), their files are protected
  # like the settings and hooks: rewriting a subagent or adding a skill under the
  # generated `olivium-` names would change what runs with their permissions.
  @protected_line ~S"""
    return r ~ /^\.claude\/(hooks(\/.*)?|settings(\.local)?\.json)$/
  """
  @protected_native ~S"""
    if (whole && r ~ /^\.claude\/(skills|agents)$/) return 1
    return r ~ /^\.claude\/(hooks(\/.*)?|settings(\.local)?\.json|skills\/olivium-[^\/]*(\/.*)?|agents\/olivium-[^\/]*)$/
  """

  @main_tool_line ~s|  tool = field(input, "tool_name")\n|
  @runner_check ~S"""
    if (tool == "Bash" && field(input, "agent_type") == "olivium-test-runner" && !runner_ok(field(input, "command"))) {
      RUNNER_REFUSED = 1
      deny("the test runner runs only: " TEST_RUNNER_LIST " (add test files or ids)")
    }
  """
  @main_reason_line ~s|  gsub(/[^ -~]/, "?", reason); gsub(/["\\\\]/, "?", reason)\n|
  @runner_reply ~S"""
    if (RUNNER_REFUSED) { printf "{\"hookSpecificOutput\":{\"hookEventName\":\"PreToolUse\",\"permissionDecision\":\"deny\",\"permissionDecisionReason\":\"Olivium guard: %s.\"}}\n", reason; exit 0 }
  """

  for anchor <- [@main_tool_line, @main_reason_line] do
    unless String.contains?(@main, anchor), do: raise("guard: anchor not found: " <> anchor)
  end

  unless String.contains?(@functions, @protected_line),
    do: raise("guard: anchor not found: " <> @protected_line)

  @spec path() :: String.t()
  def path, do: @path

  @doc "The guard script for a spec, or nil when the spec denies nothing."
  @spec render(map()) :: String.t() | nil
  def render(spec) do
    commands = for %{"action" => "deny"} = rule <- spec["permissions"]["commands"], do: rule
    paths = for %{"action" => "deny"} = rule <- spec["permissions"]["paths"], do: rule

    if commands == [] and paths == [] do
      nil
    else
      read = for %{"access" => "read", "pattern" => pattern} <- paths, do: pattern
      edit = for %{"access" => "edit", "pattern" => pattern} <- paths, do: pattern
      denied = Enum.map(commands, & &1["command"])

      {project_exact, project_prefixes} =
        for(%{"action" => "allow"} = rule <- spec["permissions"]["commands"], do: rule)
        |> Enum.filter(&String.starts_with?(&1["id"], "project."))
        |> Enum.split_with(&(&1["exact"] == true))

      # The test runner's allowed commands (profile charset: no quote, `|` or `\\`).
      runner =
        (get_in(spec, ["native", "test_runner_commands"]) || [])
        |> Enum.filter(&runner_command?/1)

      {read_name, read_path} = secret_regexes(read)
      {edit_name, edit_path} = secret_regexes(edit)
      {any_name, any_path} = secret_regexes(Enum.uniq(read ++ edit))

      constants = [
        {"READ_NAME", read_name},
        {"READ_PATH", read_path},
        {"EDIT_NAME", edit_name},
        {"EDIT_PATH", edit_path},
        {"ANY_NAME", any_name},
        {"ANY_PATH", any_path},
        {"DENY", deny_regex(denied)},
        {"PROJECT", project_regex(project_prefixes, project_exact)},
        {"RECURSIVE", if("rm -r" in denied, do: "1", else: "")},
        {"HELPER", awk_string(@helper)}
      ]

      constants =
        if runner == [],
          do: constants,
          else:
            constants ++
              [
                {"TEST_RUNNER", Enum.join(runner, "|")},
                {"TEST_RUNNER_LIST", Enum.join(runner, "; ")},
                {"RUNNER_FLAGS", Enum.join(@runner_flags, " ")}
              ]

      begin = Enum.map_join(constants, "", fn {name, value} -> ~s(  #{name} = "#{value}"\n) end)

      functions =
        if (get_in(spec, ["native", "items"]) || []) == [],
          do: @functions,
          else: String.replace(@functions, @protected_line, @protected_native, global: false)

      if runner == [] do
        @header <> functions <> "BEGIN {\n" <> begin <> @begin <> "}\n" <> @main
      else
        main =
          @main
          |> String.replace(@main_tool_line, @main_tool_line <> @runner_check, global: false)
          |> String.replace(@main_reason_line, @main_reason_line <> @runner_reply, global: false)

        @header <>
          functions <> @runner_function <> "BEGIN {\n" <> begin <> @begin <> "}\n" <> main
      end
    end
  end

  defp runner_command?(command) when is_binary(command),
    do:
      Regex.match?(
        ~r/\A[A-Za-z0-9_.\/][A-Za-z0-9_.\/:=@+,-]*(?: [A-Za-z0-9_.\/:=@+,-]+)*\z/,
        command
      )

  defp runner_command?(_), do: false

  # The helper travels as an awk string inside the single-quoted awk program, so it
  # carries no single quote of its own.
  defp awk_string(text) do
    text
    |> String.replace("\\", "\\\\")
    |> String.replace("\"", "\\\"")
    |> String.replace("'", "\\047")
    |> String.replace("\n", "\\n")
  end

  # A pattern without a slash, or `**/name/**`, names a path component; anything else
  # is matched against the whole path. Patterns use only [A-Za-z0-9_.*/@+-] (schema).
  defp secret_regexes(patterns) do
    {names, paths} =
      patterns
      |> Enum.map(&strip_globstar/1)
      |> Enum.split_with(&(not String.contains?(&1, "/")))

    {alternation("^(", Enum.map(names, &glob/1), ")$"),
     alternation("(^|/)(", Enum.map(paths, &glob/1), ")(/|$)")}
  end

  defp strip_globstar(pattern) do
    stripped =
      pattern
      |> String.replace_prefix("./", "")
      |> String.replace(~r{^(\*\*/)+}, "")
      |> String.replace(~r{(/\*\*)+$}, "")

    if stripped == "", do: pattern, else: stripped
  end

  defp glob(pattern) do
    pattern
    |> String.split("**")
    |> Enum.map_join(".*", fn part ->
      part
      |> String.graphemes()
      |> Enum.map_join(fn
        "*" -> "[^/]*"
        "." -> "[.]"
        "+" -> "[+]"
        other -> other
      end)
    end)
  end

  # A detected project command: its prefix, or the exact command for an exact rule.
  defp project_regex(prefixes, exact) do
    [
      command_regex(Enum.map(prefixes, & &1["command"]), ")( |$)"),
      command_regex(Enum.map(exact, & &1["command"]), ")$")
    ]
    |> Enum.reject(&(&1 == ""))
    |> Enum.join("|")
  end

  # The first words of a denied command, wherever a wrapper or shell put it.
  defp deny_regex(commands), do: command_regex(commands, ")( |$)")

  defp command_regex(commands, close) do
    commands
    |> Enum.map(fn command ->
      String.replace(command, ~r/[.+]/, fn character -> "[" <> character <> "]" end)
    end)
    |> then(&alternation("^(", &1, close))
  end

  defp alternation(_open, [], _close), do: ""
  defp alternation(open, items, close), do: open <> Enum.join(items, "|") <> close
end
