defmodule HarnessForge.Adapters.ClaudeCode.Rewrite do
  @moduledoc """
  The `lean-ai` PreToolUse Bash hook (`.claude/hooks/olivium-rewrite.sh`) and its data
  file `.olivium/rewrites.tsv` (`id kind match replacement`, where the replacement is
  the new argv prefix, or `tool_missing <tool>`).

  Every rewrite was verified in Docker at learn time (`olivium.learned/v1`). The hook
  looks only at the first simple command of the Bash string, after an optional
  `cd <plain path> &&`, and only when the string has no `$(`, backtick, `<(` or heredoc:

  - `wrong_runner`, `quiet_flags`: a command that starts with the match words (as whole
    words) gets the replacement words instead; the rest of the string is kept byte for
    byte, and `printf 'olivium: ran <new prefix> (verified at export)\\n'; ` goes in
    front so the agent sees what ran. A command that already starts with the
    replacement, or (`quiet_flags`) already has one of its added words, is left alone.
  - `missing_tool`: the command becomes
    `printf 'olivium: <tool> is not installed here (checked at export); skip it.\\n'`,
    unless its first simple command holds a quote (which could hide a separator). The
    rest, from the first `;`, `&`, `|` or newline that is not part of a redirection
    (`2>&1`, `&>`, `>|`) and not escaped by a backslash (`\\;`, or a backslash-newline
    line continuation, which stays part of the skipped command), is kept byte for byte
    after `; <cd prefix>true`, so
    `uv run mypy . && uv run pytest` becomes `...; true&& uv run pytest` and still runs
    the tests.

  The longest match wins (then the lower id); one rewrite per call. The hook prints
  `{"hookSpecificOutput":{"hookEventName":"PreToolUse","updatedInput":{...}}}` with the
  new command (and the call's `description`, `timeout` and `run_in_background`), or
  nothing. It never sets `permissionDecision`, so Claude Code's rules and the guard
  still decide; a guard refusal wins. It works on the JSON text of the command without
  decoding it, so the kept part is copied exactly as Claude Code sent it.

  The rows are inside the script, and the settings command runs the script only while
  its SHA-256 is the generated one and passes on only a line of that shape. Any
  failure prints nothing and exits 0.
  """

  alias HarnessForge.Contracts.Error

  @script ".claude/hooks/olivium-rewrite.sh"
  @data ".olivium/rewrites.tsv"
  @word ~r/\A[A-Za-z0-9_.\/:=+@,%-]{1,200}\z/
  @tool ~r/\A[A-Za-z0-9][A-Za-z0-9._+-]{0,63}\z/
  @output_line ~S(^[{]"hookSpecificOutput":[{]"hookEventName":"PreToolUse","updatedInput":[{]"command":"printf .olivium: .*[}][}][}]$)

  @template ~S"""
  #!/bin/sh
  # Olivium rewrite: a Claude Code PreToolUse (Bash) hook generated by Olivium Harness.
  # It replaces the start of a command with a form verified in Docker at export, and
  # prints nothing for every other command. It never approves or refuses a call.
  LC_ALL=C; export LC_ALL
  awk '
  function raw(s, key,    i, n, c, out) {
    found = 0
    if (!match(s, "\"" key "\"[ \t]*:[ \t]*\"")) return ""
    i = RSTART + RLENGTH; n = length(s); out = ""
    while (i <= n) {
      if (match(substr(s, i, 4096), /^[^"\\]+/)) { out = out substr(s, i, RLENGTH); i += RLENGTH; continue }
      c = substr(s, i, 1)
      if (c == "\"") { found = 1; return out }
      out = out substr(s, i, 2); i += 2
    }
    return ""
  }
  function boundary(c, n,    x) {
    x = substr(c, n + 1, 1)
    if (x == "" || x == " " || x == ";" || x == "&" || x == "|") return 1
    x = substr(c, n + 1, 2)
    return x == BS "n" || x == BS "t"
  }
  function starts(c, m) { return m != "" && substr(c, 1, length(m)) == m && boundary(c, length(m)) }
  function hasword(c, w,    n, k, part) { n = split(c, part, " "); for (k = 1; k <= n; k++) if (part[k] == w) return 1; return 0 }
  function firstend(c,    i, n, x, p, y) {
    n = length(c)
    for (i = 1; i <= n; i++) {
      x = substr(c, i, 1); p = ""; if (i > 1) p = substr(c, i - 1, 1)
      if (x == "&" && (p == ">" || p == "<" || substr(c, i + 1, 1) == ">")) continue
      if (x == "|" && p == ">") continue
      if (x == ";" || x == "&" || x == "|") return i
      if (x == BS) {
        y = substr(c, i + 1, 1); if (y == "n") return i
        i++
        if (y == BS) { if (substr(c, i + 1, 1) == BS) i += 2; else i++ }
      }
    }
    return n + 1
  }
  { input = input $0 "\n" }
  END {
    BS = "\\"
  @ROWS@
    c = raw(input, "command"); if (!found || c == "") exit 0
    if (index(c, "$(") || index(c, "`") || index(c, "<(") || index(c, "<<")) exit 0
    pre = ""
    if (match(c, /^cd [A-Za-z0-9_.\/~-]+ && /)) { pre = substr(c, 1, RLENGTH); c = substr(c, RLENGTH + 1) }
    e = firstend(c); first = substr(c, 1, e - 1)
    hit = 0
    for (k = 1; k <= NROWS; k++) {
      if (!starts(c, MATCH[k])) continue
      if (REPLACE[k] != "" && starts(c, REPLACE[k])) continue
      if (ADDED[k] != "") { n = split(ADDED[k], aw, " "); skip = 0; for (m = 1; m <= n; m++) if (hasword(first, aw[m])) skip = 1; if (skip) continue }
      hit = k; break
    }
    if (!hit) exit 0
    if (KIND[hit] == "missing_tool") {
      if (index(first, "\047") || index(first, BS "\"")) exit 0
      cmd = "printf \047olivium: " TOOL[hit] " is not installed here (checked at export); skip it." BS BS "n\047"
      if (pre != "" || e <= length(c)) cmd = cmd "; " pre "true" substr(c, e)
    } else {
      shown = REPLACE[hit]; gsub(/%/, "%%", shown)
      cmd = "printf \047olivium: ran " shown " (verified at export)" BS BS "n\047; " pre REPLACE[hit] substr(c, length(MATCH[hit]) + 1)
    }
    extra = ""
    d = raw(input, "description"); if (found) extra = extra ",\"description\":\"" d "\""
    if (match(input, /"timeout"[ \t]*:[ \t]*[0-9]+/)) { t = substr(input, RSTART, RLENGTH); sub(/.*:[ \t]*/, "", t); extra = extra ",\"timeout\":" t }
    if (match(input, /"run_in_background"[ \t]*:[ \t]*true/)) extra = extra ",\"run_in_background\":true"
    printf "%s\n", "{\"hookSpecificOutput\":{\"hookEventName\":\"PreToolUse\",\"updatedInput\":{\"command\":\"" cmd "\"" extra "}}}"
  }
  ' 2>/dev/null
  exit 0
  """

  @spec path() :: String.t()
  def path, do: @script

  @spec data_path() :: String.t()
  def data_path, do: @data

  @doc "The fixed shape of the only line the settings command passes on."
  @spec output_line() :: String.t()
  def output_line, do: @output_line

  @doc "Checks every rewrite that reaches the script or the data file."
  @spec validate(map()) :: :ok | {:error, Error.t()}
  def validate(%{"rewrites" => %{"items" => items, "timeout_seconds" => timeout}})
      when is_list(items) and is_integer(timeout) do
    ids = Enum.map(items, & &1["id"])

    cond do
      length(items) > 12 or length(Enum.uniq(ids)) != length(ids) ->
        invalid("spec.rewrites holds at most 12 rewrites with distinct ids")

      not Enum.all?(items, &item?/1) ->
        invalid("A rewrite needs a known kind and words of [A-Za-z0-9_./:=+@,%-]")

      true ->
        :ok
    end
  end

  def validate(%{"rewrites" => nil}), do: :ok
  def validate(%{"rewrites" => _}), do: invalid("spec.rewrites must hold a timeout and items")
  def validate(_spec), do: :ok

  defp item?(%{"id" => id, "kind" => kind, "match" => match} = item) do
    is_binary(id) and Regex.match?(~r/\Arw[0-9]{2}\z/, id) and words?(match, 6) and
      case kind do
        "missing_tool" ->
          is_nil(item["replace"]) and is_binary(item["tool"]) and
            Regex.match?(@tool, item["tool"])

        k when k in ~w(wrong_runner quiet_flags) ->
          words?(item["replace"], 10) and is_nil(item["tool"])

        _ ->
          false
      end
  end

  defp item?(_), do: false

  defp words?(list, max),
    do:
      is_list(list) and list != [] and length(list) <= max and
        Enum.all?(list, &(is_binary(&1) and Regex.match?(@word, &1)))

  defp items(%{"rewrites" => %{"items" => items}}) when is_list(items), do: items
  defp items(_spec), do: []

  @doc "`.olivium/rewrites.tsv`, written whenever the spec has `spec.rewrites`."
  @spec data_files(map()) :: map()
  def data_files(%{"rewrites" => %{"items" => _}} = spec) do
    %{@data => spec |> items() |> Enum.sort_by(& &1["id"]) |> Enum.map_join(&(row(&1) <> "\n"))}
  end

  def data_files(_spec), do: %{}

  defp row(item),
    do:
      Enum.join(
        [item["id"], item["kind"], Enum.join(item["match"], " "), replacement(item)],
        "\t"
      )

  defp replacement(%{"kind" => "missing_tool", "tool" => tool}), do: "tool_missing " <> tool
  defp replacement(item), do: Enum.join(item["replace"], " ")

  @doc "The hook script, or nil when the spec has no rewrite."
  @spec render(map()) :: String.t() | nil
  def render(spec) do
    case items(spec) do
      [] ->
        nil

      items ->
        rows =
          items
          |> Enum.sort_by(&{-length(&1["match"]), &1["id"]})
          |> Enum.with_index(1)
          |> Enum.map_join("", fn {item, k} ->
            match = Enum.join(item["match"], " ")

            {replace, added} =
              case item["kind"] do
                "missing_tool" ->
                  {"", ""}

                "quiet_flags" ->
                  words = item["replace"]

                  added =
                    if Enum.take(words, length(item["match"])) == item["match"],
                      do: Enum.drop(words, length(item["match"])),
                      else: []

                  {Enum.join(words, " "), Enum.join(added, " ")}

                _ ->
                  {Enum.join(item["replace"], " "), ""}
              end

            "  MATCH[#{k}] = \"#{match}\"; KIND[#{k}] = \"#{item["kind"]}\"; REPLACE[#{k}] = \"#{replace}\"; " <>
              "ADDED[#{k}] = \"#{added}\"; TOOL[#{k}] = \"#{item["tool"] || ""}\"\n"
          end)

        @template
        |> String.replace("@ROWS@", "  NROWS = #{length(items)}\n" <> rows)
    end
  end

  @doc """
  The settings command: PATH set to /usr/bin:/bin, the script run only while its
  SHA-256 is the generated one, and only a line of the fixed output shape passed on.
  Always exit 0.
  """
  @spec command(String.t()) :: String.t()
  def command(script) do
    digest = :crypto.hash(:sha256, script) |> Base.encode16(case: :lower)

    ~s(PATH=/usr/bin:/bin; f="$CLAUDE_PROJECT_DIR/#{@script}"; s=$\(cat "$f" 2>/dev/null\); h=$\(printf '%s\\n' "$s" | { sha256sum || shasum -a 256; } 2>/dev/null\); if [ "$h" = "#{digest}  -" ]; then /bin/sh -c "$s" olivium-rewrite 2>/dev/null | grep -E '#{@output_line}'; else echo "Olivium rewrite: #{@script} is missing, changed or cannot be checked; commands run as written." >&2; fi; true)
  end

  defp invalid(message),
    do: {:error, %Error{code: "invalid_runtime_intent", message: message, details: []}}

  # Works on the raw JSON text of tool_input.command. BS is one backslash.
end
