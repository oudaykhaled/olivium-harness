defmodule HarnessForge.Adapters.ClaudeCode.Locator do
  @moduledoc """
  The `lean-ai` index files and the UserPromptSubmit locator hook
  (`.claude/hooks/olivium-locate.sh`).

  The index (`.olivium/index/symbols.tsv`, `terms.tsv`, `tests.tsv`) is written whenever
  the spec has `spec.locator`. The hook is written only when the repository's replay
  gate passed (`spec.locator.rendered`). For each prompt it prints a card of at most
  `card_bytes` bytes that starts with `HarnessForge.Generation.Index.header/0`, or
  nothing at all. It is an awk port of `HarnessForge.Generation.Index.card/4`
  (integer arithmetic, bytewise comparisons under `LC_ALL=C`), which is the reference
  the locator gate replays; the tests compare the two byte for byte.

  The prompt is data: the script never evaluates, echoes or stores it. The card holds
  only index rows and spec values, every one of which passed a fixed character rule
  here before it was written. The script runs only while its SHA-256 is the generated
  one (`command/1`), and it reads the index only while the index files' SHA-256 is the
  generated one, so a changed file prints nothing. Any failure prints nothing on stdout
  and exits 0; a missing or changed index says so in one line on stderr.
  """

  alias HarnessForge.Contracts.Error
  alias HarnessForge.Generation.Index

  @script ".claude/hooks/olivium-locate.sh"
  @symbols ".olivium/index/symbols.tsv"
  @terms ".olivium/index/terms.tsv"
  @tests ".olivium/index/tests.tsv"
  @name ~r/\A[A-Za-z_][A-Za-z0-9_]{0,79}\z/
  @history_term ~r/\A[a-z_][a-z0-9_]{2,63}\z/
  @learned_term ~r/\A[a-z0-9_]+(?: [a-z0-9_]+)*\z/
  @digits ~r/\A[0-9]{1,7}\z/
  @word ~r/\A[A-Za-z0-9_.\/:=+@,%-]{1,200}\z/
  @kinds ~w(class def function method)
  @constant_keys ~w(path_weight symbol_weight symbol_max_locations stem_weight history_scale term_top_k learned_scale min_score min_margin min_margin_percent card_bytes)

  @template ~S"""
  #!/bin/sh
  # Olivium locator: a Claude Code UserPromptSubmit hook generated by Olivium Harness.
  # It prints a short card of the files this prompt most likely concerns, ranked from
  # .olivium/index (built from this repository's definitions and history at export), or
  # nothing. The prompt is read as data only: never evaluated, echoed or stored.
  LC_ALL=C; export LC_ALL
  d="${CLAUDE_PROJECT_DIR:-.}/.olivium"
  for f in index/symbols.tsv index/terms.tsv index/tests.tsv cochange.tsv; do
    [ -f "$d/$f" ] || { echo "Olivium locator: .olivium/$f is missing; no card." >&2; exit 0; }
  done
  h=$(cat "$d/index/symbols.tsv" "$d/index/terms.tsv" "$d/index/tests.tsv" "$d/cochange.tsv" | { sha256sum || shasum -a 256; } 2>/dev/null)
  [ "$h" = "@DIGEST@  -" ] || { echo "Olivium locator: .olivium/index changed since export; no card." >&2; exit 0; }
  awk -v S="$d/index/symbols.tsv" -v T="$d/index/terms.tsv" -v X="$d/index/tests.tsv" -v C="$d/cochange.tsv" '
  function field(s, key,    i, n, c, e, out) {
    if (!match(s, "\"" key "\"[ \t]*:[ \t]*\"")) return ""
    i = RSTART + RLENGTH; n = length(s); out = ""
    while (i <= n) {
      if (match(substr(s, i, 4096), /^[^"\\]+/)) { out = out substr(s, i, RLENGTH); i += RLENGTH; continue }
      c = substr(s, i, 1)
      if (c == "\"") break
      e = substr(s, i + 1, 1); i += 2
      if (e == "n") out = out "\n"
      else if (e == "u") { out = out " "; i += 4 }
      else if (e == "t" || e == "r" || e == "b" || e == "f") out = out " "
      else out = out e
    }
    return out
  }
  function lastpart(p) { sub(/.*\//, "", p); return p }
  function stem(p) { p = lastpart(p); if (match(p, /\.[^.]*$/)) p = substr(p, 1, RSTART - 1); return tolower(p) }
  function better(a, b) { return score[a] > score[b] || (score[a] == score[b] && (a "") < (b "")) }
  function addpath(p) { if (!(p in known)) { known[p] = 1; np++; paths[np] = p } }
  function hitless(a, b,    x, y) {
    split(a, x, "\t"); split(b, y, "\t")
    if (x[1] + 0 != y[1] + 0) return x[1] + 0 < y[1] + 0
    if ((x[2] "") != (y[2] "")) return (x[2] "") < (y[2] "")
    return x[3] + 0 < y[3] + 0
  }
  function inlist(v, list, n,    k) { for (k = 1; k <= n; k++) if ((list[k] "") == (v "")) return 1; return 0 }
  { input = input $0 "\n" }
  END {
  @ASSIGNMENTS@
    prompt = field(input, "prompt")
    if (prompt == "") exit 0
    nt = 0; rest = prompt
    while (nt < 400 && match(rest, /[A-Za-z0-9_]+/)) {
      w = substr(rest, RSTART, RLENGTH); rest = substr(rest, RSTART + RLENGTH)
      if (length(w) >= 3 && length(w) <= 64 && w ~ /^[A-Za-z_]/ && !(w in seen)) { seen[w] = 1; tok[++nt] = w; words[tolower(w)] = 1 }
    }
    norm = tolower(prompt); gsub(/[^a-z0-9_]+/, " ", norm); sub(/^ +/, "", norm); sub(/ +$/, "", norm); norm = " " norm " "
    rest = prompt
    while (match(rest, /[A-Za-z0-9_.\/-]+/)) {
      w = substr(rest, RSTART, RLENGTH); rest = substr(rest, RSTART + RLENGTH)
      sub(/\.+$/, "", w); sub(/-+$/, "", w); if (substr(w, 1, 2) == "./") w = substr(w, 3)
      named[w] = 1
    }
    ns = 0
    while ((getline line < S) > 0) {
      split(line, f, "\t"); ns++; sname[ns] = f[1]; spath[ns] = f[2]; sstart[ns] = f[3] + 0; send[ns] = f[4] + 0
      scount[f[1]]++; sidx[f[1]] = sidx[f[1]] " " ns; addpath(f[2])
    }
    close(S)
    nh = 0; nl = 0
    while ((getline line < T) > 0) {
      split(line, f, "\t"); addpath(f[2])
      if (f[4] == "history") { nh++; hpath[nh] = f[2]; hweight[nh] = f[3] + 0; hidx[f[1]] = hidx[f[1]] " " nh }
      else if (f[4] == "learned") { nl++; lterm[nl] = f[1]; lpath[nl] = f[2]; lweight[nl] = f[3] + 0 }
    }
    close(T)
    if (PATH_WEIGHT > 0) {
      for (k = 1; k <= np; k++) byname[lastpart(paths[k])]++
      for (k = 1; k <= np; k++) {
        p = paths[k]; nm = lastpart(p)
        if (p in named) score[p] += PATH_WEIGHT
        else if (index(nm, ".") && (nm in named) && byname[nm] <= SYMBOL_MAX_LOCATIONS) score[p] += int(PATH_WEIGHT / byname[nm])
      }
    }
    for (k = 1; k <= nt; k++) {
      t = tok[k]; c = scount[t] + 0
      if (c >= 1 && c <= SYMBOL_MAX_LOCATIONS) {
        n = split(sidx[t], ids, " ")
        for (m = 1; m <= n; m++) {
          r = ids[m]; p = spath[r]; score[p] += int(SYMBOL_WEIGHT / c); e = sstart[r] "\t" t "\t" send[r]
          if (p in hits) hits[p] = hits[p] "\n" e; else hits[p] = e
        }
      }
    }
    for (k = 1; k <= np; k++) { st = stem(paths[k]); if ((st in words) && !(st in stopstem)) score[paths[k]] += STEM_WEIGHT }
    for (w in words) if (w in hidx) {
      n = split(hidx[w], ids, " ")
      for (m = 1; m <= n; m++) { r = ids[m]; p = hpath[r]; contrib[p] = contrib[p] " " int(hweight[r] * HISTORY_SCALE / 100) }
    }
    for (p in contrib) {
      n = split(contrib[p], vals, " ")
      for (m = 2; m <= n; m++) { v = vals[m] + 0; for (q = m - 1; q >= 1 && vals[q] + 0 < v; q--) vals[q + 1] = vals[q]; vals[q + 1] = v }
      sum = 0; for (m = 1; m <= n && (TERM_TOP_K == 0 || m <= TERM_TOP_K); m++) sum += vals[m] + 0
      score[p] += sum
    }
    for (r = 1; r <= nl; r++) if (index(norm, " " lterm[r] " ")) score[lpath[r]] += int(lweight[r] * LEARNED_SCALE / 100)
    nb = 0
    for (p in score) if (score[p] > 0) {
      for (k = 1; k <= nb; k++) if (better(p, top[k])) break
      if (k <= 3) { for (m = (nb < 3 ? nb + 1 : 3); m > k; m--) top[m] = top[m - 1]; top[k] = p; if (nb < 3) nb++ }
    }
    if (nb == 0) exit 0
    best = score[top[1]]; second = nb >= 2 ? score[top[2]] : 0
    if (best < MIN_SCORE) exit 0
    if (!(top[1] in hits) && !(best - second >= MIN_MARGIN && best * 100 >= second * (100 + MIN_MARGIN_PERCENT))) exit 0
    nlines = 0
    for (k = 1; k <= nb; k++) {
      p = top[k]; spans = ""
      if (p in hits) {
        n = split(hits[p], hl, "\n"); u = 0
        for (m = 1; m <= n; m++) if (!inlist(hl[m], uh, u)) uh[++u] = hl[m]
        for (m = 2; m <= u; m++) { v = uh[m]; for (q = m - 1; q >= 1 && hitless(v, uh[q]); q--) uh[q + 1] = uh[q]; uh[q + 1] = v }
        for (m = 1; m <= u && m <= 3; m++) { split(uh[m], x, "\t"); spans = spans (m > 1 ? ", " : "") x[2] " " x[1] "-" x[3] }
      }
      lines[++nlines] = spans == "" ? "- " p : "- " p ": " spans; lpaths[nlines] = p
    }
    nx = 0
    while ((getline line < X) > 0) { split(line, f, "\t"); nx++; xsrc[nx] = f[1]; xtest[nx] = f[2]; xsup[nx] = f[3] + 0 }
    close(X)
    ntests = 0
    for (k = 1; k <= nb; k++) {
      c = 0
      for (r = 1; r <= nx; r++) if ((xsrc[r] "") == (top[k] "")) cand[++c] = r
      for (m = 2; m <= c; m++) { v = cand[m]; for (q = m - 1; q >= 1 && (xsup[cand[q]] < xsup[v] || (xsup[cand[q]] == xsup[v] && (xtest[cand[q]] "") > (xtest[v] ""))); q--) cand[q + 1] = cand[q]; cand[q + 1] = v }
      for (m = 1; m <= c && ntests < 2; m++) { t = xtest[cand[m]]; if (!inlist(t, top, nb) && !inlist(t, tests, ntests)) tests[++ntests] = t }
    }
    if (ntests > 0) { s = "Tests: " tests[1]; if (ntests > 1) s = s ", " tests[2]; lines[++nlines] = s }
    c = 0
    while ((getline line < C) > 0) { split(line, f, "\t"); if ((f[1] "") == (top[1] "")) { c++; cpart[c] = f[2]; csup[c] = f[3] + 0 } }
    close(C)
    for (m = 2; m <= c; m++) { v = cpart[m]; vs = csup[m]; for (q = m - 1; q >= 1 && (csup[q] < vs || (csup[q] == vs && (cpart[q] "") > (v ""))); q--) { cpart[q + 1] = cpart[q]; csup[q + 1] = csup[q] } cpart[q + 1] = v; csup[q + 1] = vs }
    npart = 0
    for (m = 1; m <= c && npart < 2; m++) { v = cpart[m]; if (!inlist(v, top, nb) && !inlist(v, tests, ntests) && !inlist(v, parts, npart)) parts[++npart] = v }
    if (npart > 0) { s = "Co-changed: " parts[1]; if (npart > 1) s = s ", " parts[2]; lines[++nlines] = s }
    if (NRUN > 0 && ntests > 0) {
      s = ""; hasfile = 0
      for (m = 1; m <= NRUN; m++) { if (RUN[m] == "{file}") { hasfile = 1; v = tests[1] } else v = RUN[m]; s = s (m > 1 ? " " : "") v }
      if (hasfile) lines[++nlines] = "Run: " s
    }
    for (k = 1; k <= NPIT; k++) {
      n = split(PITPATHS[k], pp, "\t"); on = 0
      for (m = 1; m <= n; m++) if (inlist(pp[m], top, nb)) on = 1
      if (!on) continue
      n = split(PITTRIG[k], pt, "\t"); trig = 0
      for (m = 1; m <= n; m++) if (index(norm, " " pt[m] " ")) trig = 1
      if (trig) { lines[++nlines] = "Pitfall: " PITTEXT[k]; break }
    }
    out = HEADER "\n"
    for (k = 1; k <= nlines; k++) { if (length(out) + length(lines[k]) + 1 > CARD_BYTES) break; out = out lines[k] "\n" }
    printf "%s", out
  }
  ' 2>/dev/null
  exit 0
  """

  @spec path() :: String.t()
  def path, do: @script

  @doc "The exported index paths, in the order the hook checksums them (with the co-change file)."
  @spec index_paths() :: [String.t()]
  def index_paths, do: [@symbols, @terms, @tests]

  @doc """
  Checks every row and value that reaches an index file or the hook. A value outside
  the rules refuses the export; nothing is repaired or dropped here.
  """
  @spec validate(map()) :: :ok | {:error, Error.t()}
  def validate(%{"locator" => %{} = locator}) do
    index = locator["index"] || %{}
    constants = locator["constants"] || %{}

    checks = [
      {Enum.all?(@constant_keys, &(is_integer(constants[&1]) and constants[&1] >= 0)),
       "constants"},
      {is_list(index["symbols"]) and Enum.all?(index["symbols"], &symbol_row?/1),
       "symbols.tsv rows"},
      {is_list(index["terms"]) and Enum.all?(index["terms"], &term_row?/1), "terms.tsv rows"},
      {is_list(index["tests"]) and Enum.all?(index["tests"], &test_row?/1), "tests.tsv rows"},
      {sorted_unique?(index["symbols"]) and sorted_unique?(index["terms"]) and
         sorted_unique?(index["tests"]), "index rows must be sorted and unique"},
      {is_list(locator["stem_stopwords"]) and
         Enum.all?(locator["stem_stopwords"], &Regex.match?(~r/\A[a-z0-9_]{1,64}\z/, &1)),
       "stem_stopwords"},
      {test_command?(locator["test_command"]), "test_command"},
      {is_list(locator["pitfalls"]) and Enum.all?(locator["pitfalls"], &pitfall?/1), "pitfalls"}
    ]

    case Enum.find(checks, fn {ok, _} -> ok != true end) do
      nil -> :ok
      {_, what} -> invalid("spec.locator has an invalid #{what}")
    end
  end

  def validate(%{"locator" => nil}), do: :ok
  def validate(%{"locator" => _}), do: invalid("spec.locator must be an object")
  def validate(_spec), do: :ok

  defp symbol_row?(row) do
    case split(row) do
      [name, path, start, stop, kind] ->
        Regex.match?(@name, name) and Index.plain_path?(path) and Regex.match?(@digits, start) and
          Regex.match?(@digits, stop) and kind in @kinds

      _ ->
        false
    end
  end

  defp term_row?(row) do
    case split(row) do
      [term, path, weight, "history"] ->
        Regex.match?(@history_term, term) and Index.plain_path?(path) and weight?(weight)

      [term, path, weight, "learned"] ->
        byte_size(term) <= 64 and Regex.match?(@learned_term, term) and Index.plain_path?(path) and
          weight?(weight)

      _ ->
        false
    end
  end

  defp test_row?(row) do
    case split(row) do
      [source, test, support, kind] ->
        Index.plain_path?(source) and Index.plain_path?(test) and Regex.match?(@digits, support) and
          kind in ~w(history name)

      _ ->
        false
    end
  end

  defp weight?(text), do: Regex.match?(@digits, text) and String.to_integer(text) in 1..1000

  defp split(row) when is_binary(row), do: String.split(row, "\t")
  defp split(_), do: []

  defp sorted_unique?(rows) when is_list(rows), do: rows == rows |> Enum.uniq() |> Enum.sort()
  defp sorted_unique?(_), do: false

  defp test_command?(nil), do: true

  defp test_command?(argv) when is_list(argv) and argv != [] and length(argv) <= 16,
    do: Enum.all?(argv, &(is_binary(&1) and (&1 == "{file}" or Regex.match?(@word, &1))))

  defp test_command?(_), do: false

  defp pitfall?(%{"id" => id, "paths" => paths, "triggers" => triggers, "text" => text}) do
    is_binary(id) and Regex.match?(~r/\Ap[0-9]{2}\z/, id) and is_list(paths) and paths != [] and
      Enum.all?(paths, &Index.plain_path?/1) and is_list(triggers) and triggers != [] and
      Enum.all?(triggers, &(is_binary(&1) and Regex.match?(@learned_term, &1))) and
      is_binary(text) and
      Regex.match?(~r/\A[\x20-\x7e]{20,200}\z/, text)
  end

  defp pitfall?(_), do: false

  @doc "The index files: one row per line, each ending in a newline (empty files stay empty)."
  @spec data_files(map()) :: map()
  def data_files(%{"locator" => %{"index" => index}}) do
    %{
      @symbols => lines(index["symbols"]),
      @terms => lines(index["terms"]),
      @tests => lines(index["tests"])
    }
  end

  def data_files(_spec), do: %{}

  defp lines(rows), do: Enum.map_join(rows, &(&1 <> "\n"))

  @doc """
  The hook script, or nil when the gate did not pass. `cochange` is the exported
  `.olivium/cochange.tsv`, which the card reads for co-change partners.
  """
  @spec render(map(), String.t()) :: String.t() | nil
  def render(%{"locator" => %{"rendered" => true} = locator} = spec, cochange) do
    files = data_files(spec)
    digest = sha256(files[@symbols] <> files[@terms] <> files[@tests] <> cochange)
    constants = locator["constants"]

    assignments =
      Enum.map_join(@constant_keys, "", fn key ->
        "  #{String.upcase(key)} = #{constants[key]}\n"
      end) <>
        Enum.map_join(locator["stem_stopwords"], "", &"  stopstem[\"#{&1}\"] = 1\n") <>
        run_assignments(locator["test_command"]) <>
        pitfall_assignments(locator["pitfalls"]) <>
        "  HEADER = \"#{awk_string(Index.header())}\"\n"

    String.replace(@template, "@DIGEST@", digest)
    |> String.replace("@ASSIGNMENTS@", assignments)
  end

  def render(_spec, _cochange), do: nil

  defp run_assignments(nil), do: "  NRUN = 0\n"

  defp run_assignments(argv) do
    "  NRUN = #{length(argv)}\n" <>
      (argv
       |> Enum.with_index(1)
       |> Enum.map_join("", fn {word, k} -> "  RUN[#{k}] = \"#{awk_string(word)}\"\n" end))
  end

  defp pitfall_assignments(pitfalls) do
    "  NPIT = #{length(pitfalls)}\n" <>
      (pitfalls
       |> Enum.sort_by(& &1["id"])
       |> Enum.with_index(1)
       |> Enum.map_join("", fn {pitfall, k} ->
         "  PITTEXT[#{k}] = \"#{awk_string(pitfall["text"])}\"\n" <>
           "  PITPATHS[#{k}] = \"#{awk_string(Enum.join(pitfall["paths"], "\t"))}\"\n" <>
           "  PITTRIG[#{k}] = \"#{awk_string(Enum.join(pitfall["triggers"], "\t"))}\"\n"
       end))
  end

  # An awk string literal inside a single-quoted sh word: backslash and double quote
  # escaped for awk, a single quote as the octal escape \047, a tab as \t.
  defp awk_string(text) do
    text
    |> String.replace("\\", "\\\\")
    |> String.replace("\"", "\\\"")
    |> String.replace("'", "\\047")
    |> String.replace("\t", "\\t")
  end

  @doc """
  The settings command. It sets PATH to /usr/bin:/bin, reads the script once and runs
  it only while its SHA-256 is the generated one; otherwise it says so on stderr. It
  always exits 0, so a missing or failing locator never blocks a prompt.
  """
  @spec command(String.t()) :: String.t()
  def command(script) do
    digest = sha256(script)

    ~s(PATH=/usr/bin:/bin; f="$CLAUDE_PROJECT_DIR/#{@script}"; s=$\(cat "$f" 2>/dev/null\); h=$\(printf '%s\\n' "$s" | { sha256sum || shasum -a 256; } 2>/dev/null\); if [ "$h" = "#{digest}  -" ]; then /bin/sh -c "$s" olivium-locate 2>/dev/null; else echo "Olivium locator: #{@script} is missing, changed or cannot be checked; no card." >&2; fi; true)
  end

  defp sha256(bytes), do: :crypto.hash(:sha256, bytes) |> Base.encode16(case: :lower)

  defp invalid(message),
    do: {:error, %Error{code: "invalid_runtime_intent", message: message, details: []}}

  # The awk program mirrors Index.rank/3 and Index.card/4. Paths are compared as
  # strings (`(a "") < (b "")`), never as numbers.
end
