defmodule HarnessForge.Models.Ledger do
  @moduledoc "Durable reservations shared by authoring and runtime inference. Uncertain calls retain their entire reservation."
  import Ecto.Query
  alias HarnessForge.{Repo, Workspaces, Contracts}
  alias HarnessForge.Models.{Budget, Request}
  alias HarnessForge.Evidence.Store

  @defaults %{
    "max_requests" => 10,
    "max_tokens" => 100_000,
    "max_estimated_microusd" => 1_000_000
  }
  def defaults, do: @defaults

  def start_run(run_id, attrs \\ @defaults) do
    with :ok <- HarnessForge.Models.RunAuthorization.legacy_budget_allowed(run_id),
         do: start_checked(run_id, attrs)
  end

  @doc false
  # Internal legacy callers may resume saved caps without requesting different
  # caps. Creation defaults apply only when no budget exists. The ordinary
  # setup/retirement fence still runs before either lookup or creation.
  def reopen_run(run_id, creation_limits \\ @defaults) do
    with :ok <- HarnessForge.Models.RunAuthorization.legacy_budget_allowed(run_id) do
      case budget(run_id) do
        {:ok, saved} -> start_run(run_id, Map.take(saved, Map.keys(@defaults)))
        {:error, :budget_not_found} -> start_run(run_id, creation_limits)
        error -> error
      end
    end
  end

  @doc false
  def start_authorized_run(run_id, attrs) do
    with :ok <- HarnessForge.Models.RunAuthorization.budget_creation_allowed(run_id),
         do: start_checked(run_id, attrs)
  end

  defp start_checked(run_id, attrs) do
    with true <- identifier?(run_id) and is_map(attrs),
         true <- Map.keys(attrs) -- Map.keys(@defaults) == [],
         limits = Map.merge(@defaults, attrs),
         true <-
           Enum.all?(
             ~w(max_requests max_tokens),
             &(is_integer(limits[&1]) and limits[&1] in 1..1_000_000_000)
           ),
         true <-
           is_integer(limits["max_estimated_microusd"]) and
             limits["max_estimated_microusd"] in 0..1_000_000_000 do
      record = %Budget{
        workspace_id: Workspaces.current_id(),
        run_id: run_id,
        max_requests: limits["max_requests"],
        max_tokens: limits["max_tokens"],
        max_estimated_microusd: limits["max_estimated_microusd"]
      }

      case Repo.insert(record, on_conflict: :nothing, conflict_target: [:workspace_id, :run_id]) do
        {:ok, _} ->
          with {:ok, stored} <- budget(run_id),
               true <- Map.take(stored, Map.keys(@defaults)) == limits,
               do: {:ok, stored},
               else: (_ -> {:error, :invalid_budget})

        {:error, _} ->
          {:error, :budget_unavailable}
      end
    else
      _ -> {:error, :invalid_budget}
    end
  end

  def budget(run_id) do
    case Repo.one(from b in Store.scoped(Budget), where: b.run_id == ^run_id) do
      nil -> {:error, :budget_not_found}
      budget -> {:ok, Store.dto(budget)}
    end
  end

  def reserve(request, config, input_tokens) do
    with :ok <- HarnessForge.Models.RunAuthorization.legacy_budget_allowed(request["run_id"]),
         do: reserve_checked(request, config, input_tokens)
  end

  defp reserve_checked(request, config, input_tokens) do
    tokens = input_tokens + request["max_output_tokens"]
    cost = estimate(config, input_tokens, request["max_output_tokens"])
    workspace = Workspaces.current_id()
    run = request["run_id"]
    request_id = request["request_id"]
    now = Store.now()

    # INSERT first obtains SQLite's write lock before reading/updating the run.
    # The unique key fences retries even if a caller died after network dispatch.
    Store.transaction(fn ->
      record = %Request{
        workspace_id: workspace,
        run_id: run,
        request_id: request_id,
        provider: config["provider"],
        model: config["model"],
        fingerprint: Contracts.digest(Map.delete(request, "request_id")),
        reserved_tokens: tokens,
        reserved_estimated_microusd: cost
      }

      changeset =
        Ecto.Changeset.change(record)
        |> Ecto.Changeset.unique_constraint([:workspace_id, :run_id, :request_id])

      case Repo.insert(changeset,
             on_conflict: :nothing,
             conflict_target: [:workspace_id, :run_id, :request_id],
             returning: true
           ) do
        {:ok, %{inserted_at: nil}} ->
          {:error, :request_already_dispatched}

        {:ok, reserved} ->
          # Ecto's :nothing still populates autogenerated fields; use the stored
          # row's id to determine whether this attempt owns the dispatch.
          stored =
            Repo.one!(
              from r in Store.scoped(Request),
                where: r.run_id == ^run and r.request_id == ^request_id
            )

          pending =
            from r in Store.scoped(Request),
              where:
                r.run_id == ^run and
                  r.fingerprint == ^record.fingerprint and r.id != ^stored.id and
                  r.state in ["dispatched", "uncertain"]

          cond do
            stored.id != reserved.id ->
              {:error, :request_already_dispatched}

            Repo.exists?(pending) ->
              {:error, :request_outcome_unknown}

            true ->
              query =
                from b in Store.scoped(Budget),
                  where:
                    b.run_id == ^run and b.reserved_requests + 1 <= b.max_requests and
                      b.reserved_tokens + ^tokens <= b.max_tokens and
                      b.reserved_estimated_microusd + ^cost <= b.max_estimated_microusd

              case Repo.update_all(query,
                     inc: [
                       reserved_requests: 1,
                       reserved_tokens: tokens,
                       reserved_estimated_microusd: cost
                     ],
                     set: [updated_at: now]
                   ) do
                {1, _} -> {:ok, Store.dto(stored)}
                _ -> {:error, :budget_exhausted}
              end
          end

        {:error, _} ->
          {:error, :request_already_dispatched}
      end
    end)
  end

  @doc false
  def reserve_stage_attempt(attempt, pin, operation_id) do
    # Attempt identity is a durable unique request key, never fingerprint padding.
    # Identical uncertain payloads retain the ordinary run-level retry fence.
    with {:ok, budget_id} <-
           HarnessForge.Models.RunAuthorization.budget_for_operation(operation_id, pin) do
      request = %{
        "run_id" => budget_id,
        "request_id" => attempt["attempt_id"],
        "purpose" => "stage",
        "stage_config_id" => pin["id"],
        "manifest_digest" => attempt["context_manifest_digest"],
        "payload_hash" => attempt["payload_sha256"],
        "max_output_tokens" => attempt["max_output_tokens"]
      }

      config = %{
        "provider" => pin["provider"],
        "model" => pin["model"],
        "input_microusd_per_million" => pin["input_rate"],
        "output_microusd_per_million" => pin["output_rate"]
      }

      reserve_checked(request, config, byte_size(attempt["body"]) + 1024)
    end
  end

  def reconcile(reservation, outcome, config) do
    Store.transaction(fn ->
      query =
        from r in Store.scoped(Request),
          where: r.id == ^reservation["id"] and r.state == "dispatched"

      case outcome do
        {:ok, %{input_tokens: input, output_tokens: output}}
        when is_integer(input) and input >= 0 and is_integer(output) and output >= 0 ->
          actual_tokens = input + output
          actual_cost = estimate(config, input, output)

          {count, _} =
            Repo.update_all(query,
              set: [
                state: "completed",
                usage_status: "reported",
                billing_status:
                  if(config["provider"] == "ollama",
                    do: "local_unpriced",
                    else: "estimated"
                  ),
                input_tokens: input,
                output_tokens: output,
                updated_at: Store.now()
              ]
            )

          if count == 1 do
            # Never release unknown capacity. Reported overruns remain visible
            # and prevent further dispatches beyond the configured hard limits.
            budgets = from b in Store.scoped(Budget), where: b.run_id == ^reservation["run_id"]

            Repo.update_all(budgets,
              inc: [
                reserved_tokens: actual_tokens - reservation["reserved_tokens"],
                reserved_estimated_microusd:
                  actual_cost - reservation["reserved_estimated_microusd"]
              ]
            )
          end

          {:ok, :reconciled}

        _ ->
          Repo.update_all(query,
            set: [
              state: "uncertain",
              usage_status: "unknown",
              billing_status: "unknown",
              updated_at: Store.now()
            ]
          )

          {:ok, :uncertain}
      end
    end)
  end

  def list_requests(run_id) do
    {:ok,
     Repo.all(
       from r in Store.scoped(Request), where: r.run_id == ^run_id, order_by: r.inserted_at
     )
     |> Enum.map(&Store.dto/1)}
  end

  def estimate(%{"provider" => "ollama"}, _, _), do: 0

  def estimate(config, input, output),
    do:
      div(
        input * config["input_microusd_per_million"] +
          output * config["output_microusd_per_million"] + 999_999,
        1_000_000
      )

  def identifier?(value),
    do: is_binary(value) and Regex.match?(~r/\A[A-Za-z0-9][A-Za-z0-9_.:-]{0,199}\z/, value)
end
